def _humanize_code(code: str) -> str:
    """Format an unknown SCREAMING_SNAKE_CASE code into clean Title Case."""
    words = code.replace("_", " ").strip().lower().split()
    return " ".join(w.capitalize() for w in words) if words else code


def translate_violation(code: str) -> dict[str, str]:
    """Translate a single security policy code into plain-English guidance.

    Args:
        code: Technical code string (e.g. 'IP_LITERAL_HOST', 'MAGIC_BYTE_MISMATCH').

    Returns:
        Structured dictionary with title, category, severity, meaning, tactic, and action.
    """
    clean_code = str(code).strip().upper()
    if clean_code in _THREAT_TRANSLATIONS:
        entry = dict(_THREAT_TRANSLATIONS[clean_code])
        entry["code"] = clean_code
        return entry

    # Fallback for dynamic or novel security codes
    title = _humanize_code(clean_code)
    return {
        "code": clean_code,
        "title": f"Security Anomaly: {title}",
        "category": "Security Policy Rule",
        "severity": "Medium",
        "meaning": f"The security engine identified an abnormal attribute matching pattern: '{clean_code}'.",
        "tactic": "Suspicious structural or behavioral patterns that deviate from normal enterprise traffic.",
        "action": "Review this item carefully with your security team before interacting with it.",
    }


def explain_risk_score(score: int, verdict: str) -> dict[str, str]:
    """Provide a user-friendly summary of what a risk score and verdict mean."""
    v = str(verdict).upper()
    int_score = max(0, int(score))

    if v == "MALICIOUS" or int_score >= 8:
        return {
            "verdict_plain": "Danger: Confirmed Threat",
            "badge_color": "red",
            "summary": f"Risk Score {int_score}/10 — This item exhibits severe indicators of an active phishing attack, malware payload, or evasion attempt.",
            "recommended_action": "Do NOT open links or attachments. Automated quarantine has isolated this message.",
        }
    elif v == "SUSPICIOUS" or int_score >= 3:
        return {
            "verdict_plain": "Caution: Suspicious Signals Detected",
            "badge_color": "amber",
            "summary": f"Risk Score {int_score}/10 — This item has unusual characteristics that may indicate an emerging lure or unverified sender.",
            "recommended_action": "Verify the sender via an independent communication channel (phone, chat) before clicking.",
        }
    else:
        return {
            "verdict_plain": "Safe: Clean & Verified",
            "badge_color": "emerald",
            "summary": f"Risk Score {int_score}/10 — No suspicious steganography, file disguises, or threat indicators were detected.",
            "recommended_action": "Standard enterprise communication. No immediate security threat identified.",
        }


def get_plain_english_verdict(verdict: str) -> str:
    """Return a plain-English label for standard security verdicts."""
    v = str(verdict).upper()
    if v == "MALICIOUS":
        return "🚨 Confirmed Threat (High Risk)"
    elif v == "SUSPICIOUS":
        return "⚠️ Suspicious (Proceed with Caution)"
    elif v == "SAFE":
        return "✅ Verified Safe (No Threat Detected)"
    return "❓ Unclassified"


def translate_report(report_or_dict: dict[str, Any]) -> dict[str, Any]:
    """Translate an entire scan report into plain-English summaries.

    Accepts scan reports from URL analysis, HTML evasion inspection,
    attachment inspection, or Gmail API ingestion.

    Returns:
        Dictionary containing:
        - plain_verdict: User-friendly verdict headline
        - risk_explanation: Summary and recommended actions
        - translated_violations: List of plain-English explanation dicts
        - key_takeaway: Single-sentence executive takeaway
    """
    if not isinstance(report_or_dict, dict):
        return {
            "plain_verdict": "Unknown",
            "risk_explanation": explain_risk_score(0, "UNKNOWN"),
            "translated_violations": [],
            "key_takeaway": "No data available for analysis.",
        }

    verdict = str(report_or_dict.get("verdict", "SAFE")).upper()
    score = int(report_or_dict.get("risk_score", 0))

    # Extract violations whether stored as strings or dicts
    raw_violations = report_or_dict.get("violations", []) or []
    if not raw_violations and "policy_violations" in report_or_dict:
        raw_violations = report_or_dict.get("policy_violations", []) or []

    translated_list: list[dict[str, str]] = []
    seen_codes: set[str] = set()

    for item in raw_violations:
        code = ""
        if isinstance(item, dict):
            code = item.get("code") or item.get("name") or ""
        elif isinstance(item, str):
            code = item

        if code and code not in seen_codes:
            seen_codes.add(code)
            translated_list.append(translate_violation(code))

    risk_info = explain_risk_score(score, verdict)

    if verdict == "MALICIOUS":
        takeaway = f"CRITICAL: Avoid interaction. Detected {len(translated_list)} dangerous evasion/threat patterns."
    elif verdict == "SUSPICIOUS":
        takeaway = f"CAUTION: Unusual patterns detected ({len(translated_list)} warning flags). Do not submit credentials."
    else:
        takeaway = "SAFE: No malicious indicators, hidden text, or deceptive file signatures found."

    return {
        "verdict_plain": get_plain_english_verdict(verdict),
        "risk_explanation": risk_info,
        "translated_violations": translated_list,
        "violation_count": len(translated_list),
        "key_takeaway": takeaway,
    }
